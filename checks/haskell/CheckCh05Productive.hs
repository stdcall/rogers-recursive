-- | Checks of chapter 7, sections 7.3, 7.7-7.9 (pp. 115, 122-139): the
-- iteration of a productive function in the proof of theorem X, the
-- diagonal function of example 2 of section 7.3, the formulas of
-- elementary arithmetic of section 7.8 and the deducibility of exercise
-- 7-62 (Craig's theorem) on models.
--
-- Run: runghc -ichecks/haskell checks/haskell/CheckCh05Productive.hs
--
-- What is checked and where the expectations come from:
-- * Theorem X (pp. 122-123, th:productive-infinite-re-subset): k(0) = z_0,
--   k(n + 1) = f(h psi k(n), k(n)), g = psi k, with W_(f(x, y)) = W_x union
--   W_y, W_(h(x)) = {x}, on a model numbering of the finite sets (W_z =
--   D_z, the canonical indices of section 5.6) and a model psi that is
--   defined exactly at the z with W_z in A and then gives an element of A -
--   W_z.  Checked: k(n) is an index of {g(0), ..., g(n - 1)} (k(n)
--   "corresponds to z_n"), g is one-one with values in A, and psi(z_(n +
--   1)) is defined because W_(z_(n + 1)) = {g(0), ..., g(n)} is in A (the
--   corrected premise of p. 122; with the printed W_(z_n) the premise
--   concerns another set, smaller by g(n)).  A model psi of this kind is
--   not a productive function (A is decidable here); only the bookkeeping
--   of the iteration is checked.
-- * Example 2 of section 7.3 (p. 115, exm:total-productive) and exercise
--   7-17 (ex:verify-productive-example): phi_(g(x))(z) = 0 while the
--   computation of phi_(f'(x))(0) has not stopped within z steps, else
--   phi_(phi_(f'(x))(z - z_0))(z) + 1, on a toy numbering of total
--   functions: phi_(g(x)) is total, differs from phi_w at z_0 + j for w =
--   phi_(f'(x))(j), and is lambda z [0] when W_x is empty.
-- * Section 7.8 (pp. 130-131): the wff (forall a) [not a = 2 => (exists b)
--   a = b x b] is false (a = 3); the axioms of the footnote of p. 131 (as
--   corrected: (forall a) [not 0 = a + 1], a x (b + 1) = (a x b) + a) hold
--   for a, b <= 100, and so do the numeral axioms (...((1 + 1) + 1) ... +
--   1) = x.
-- * Exercise 7-62 (pp. 138-139, ex:craig-theorem) on the deducibility
--   generated by the three rules of the exercise ((x & y) from {x, y}, x
--   and y from (x & y)), with formulas of bounded depth: (b) A in A~ and
--   A~~ = A~; (c) (A union B)~ /= A~ union B~ for A = {p}, B = {q}; (d) the
--   printed A~ = B~ (the tilde over B, as read) is satisfiable, while A~ =
--   B fails for B = {p} and every A (A~ contains (p & p)); the hint: x,
--   (x & x), ((x & x) & x), ... are interderivable, and Craig's set {(...
--   (f(n) & f(n)) ... & f(n)) with n + 1 terms} is decidable by the shape
--   of the formula and has the same consequences as Val f.
--
-- Not established: productivity, recursive enumerability and the
-- incompleteness results themselves (they rest on Church's thesis and on
-- arithmetization, which are not modelled); statements beyond the models
-- and bounds above.
module Main (main) where

import Data.Bits (testBit, (.|.))
import qualified Data.List as L
import Data.List (nub, sort)

import Harness

------------------------------------------------------------------------
-- Theorem X on the model numbering W_z = D_z

dSet :: Integer -> [Integer]
dSet x = [z | z <- [0 .. 200], testBit x (fromInteger z)]

isPrime :: Integer -> Bool
isPrime n = n >= 2 && all (\d -> n `mod` d /= 0) (takeWhile (\d -> d * d <= n) [2 ..])

-- | Model "productive" functions for a decidable A: defined exactly when
-- W_z is in A, then an element of A - W_z.
type Model = (String, Integer -> Bool, Integer -> Maybe Integer)

models :: [Model]
models =
  [ ("A = primes, psi = the least element of A - W_z", isPrime, \z -> leastNew isPrime z)
  , ( "A = 3N + 1, psi = the element of A - W_z after max W_z"
    , \x -> x `mod` 3 == 1
    , \z -> let ds = dSet z
            in if all (\x -> x `mod` 3 == 1) ds
                 then Just (head [a | a <- [maybe 1 (+ 1) (safeMax ds) ..], a `mod` 3 == 1])
                 else Nothing ) ]
  where
    leastNew p z = let ds = dSet z in if all p ds then Just (head [a | a <- [0 ..], p a, a `notElem` ds]) else Nothing
    safeMax [] = Nothing
    safeMax xs = Just (maximum xs)

fUnion :: Integer -> Integer -> Integer
fUnion = (.|.)

hSingleton :: Integer -> Integer
hSingleton x = 2 ^ x

------------------------------------------------------------------------
-- Example 2 of section 7.3 on a toy numbering of total functions

phiToy :: Integer -> Integer -> Integer
phiToy i z = (i * z + i * i + 3) `mod` (i + 5)

diag :: Maybe (Integer, Integer -> Integer) -> Integer -> Integer
diag Nothing _ = 0
diag (Just (z0, e)) z
  | z < z0 = 0                                   -- not stopped within z steps
  | otherwise = phiToy (e (z - z0)) z + 1

------------------------------------------------------------------------
-- Formulas with & (exercise 7-62)

data F = At Int | And F F deriving (Eq, Ord, Show)

depth :: F -> Int
depth (At _) = 0
depth (And a b) = 1 + max (depth a) (depth b)

-- | The deductive closure under the three rules, restricted to formulas of
-- depth <= d (a sound part of the closure).
closure :: Int -> [F] -> [F]
closure d s0 = go (uniq (filter ((<= d) . depth) s0))
  where
    go s = let new = uniq (s ++ [w | And a b <- s, w <- [a, b]]
                             ++ [And a b | a <- s, b <- s, 1 + max (depth a) (depth b) <= d])
           in if new == s then s else go new

uniq :: Ord a => [a] -> [a]
uniq = map head . L.group . sort

conj :: Int -> F -> F
conj 1 x = x
conj k x = And (conj (k - 1) x) x

formulas :: Int -> [Int] -> [F]
formulas 0 atoms = map At atoms
formulas d atoms = let r = formulas (d - 1) atoms in uniq (map At atoms ++ [And a b | a <- r, b <- r])

-- | Craig's set for an enumeration f of atoms: w is in it iff w is
-- conj k (At a) with f(k - 1) = a.
inCraig :: (Int -> Int) -> F -> Bool
inCraig f w = case peel w 1 of
  Just (k, a) -> f (k - 1) == a
  Nothing -> False
  where
    peel (At a) k = Just (k, a)
    peel (And u (At a)) k = case peel u (k + 1) of
      Just (k', a') | a' == a -> Just (k', a)
      _ -> Nothing
    peel _ _ = Nothing

------------------------------------------------------------------------

main :: IO ()
main = do
  c <- newCounter

  group c "theorem X: k(n) indexes {g(0), ..., g(n - 1)}, g one-one into A"
    ( concat
      [ [ (name ++ ": psi(k(" ++ show n ++ ")) defined, W_k(n) = {g(0), ..., g(n - 1)}",
           sort (dSet (ks !! n)) == sort (take n gs))
        | n <- [0 .. 40], psi (ks !! n) /= Nothing || error "psi undefined" ]
        ++ [ (name ++ ": g(0..40) one-one, in A", length (nub (take 41 gs)) == 41 && all inA (take 41 gs))
           , (name ++ ": k(0) = z_0, the index of the empty set", head ks == 0 && null (dSet 0)) ]
        ++ [ (name ++ ": W_(z_(n + 1)) in A, psi(z_(n + 1)) defined, W_(z_n) the smaller set, n = " ++ show n,
              all inA (dSet (ks !! (n + 1))) && psi (ks !! (n + 1)) /= Nothing
              && length (dSet (ks !! (n + 1))) == length (dSet (ks !! n)) + 1)
           | n <- [0 .. 39] ]
        ++ [ (name ++ ": the model psi is undefined off A", psi (hSingleton (head [x | x <- [0 ..], not (inA x)])) == Nothing) ]
      | (name, inA, psi) <- models
      , let ks = iterate (\k -> fUnion (hSingleton (unJust (psi k))) k) 0
            gs = map (unJust . psi) ks ] )

  group c "example 2 of 7.3 (exercise 7-17): the diagonal function g on a toy numbering"
    ( [ ("z_0 = " ++ show z0 ++ ", e = " ++ ename ++ ": differs from phi_e(j) at z_0 + j, j = " ++ show j,
         diag (Just (z0, e)) (z0 + j) /= phiToy (e j) (z0 + j))
      | z0 <- [0, 1, 5, 17]
      , (ename, e) <- [("j mod 7", (`mod` 7)), ("3", const 3), ("j^2 mod 11 + 1", \j -> (j * j) `mod` 11 + 1)]
      , j <- [0 .. 60] ]
      ++ [ ("z_0 = " ++ show z0 ++ ": 0 below z_0", all (\z -> diag (Just (z0, (`mod` 7))) z == 0) [0 .. z0 - 1])
         | z0 <- [0, 1, 5, 17] ]
      ++ [("W_x empty: g(x) computes lambda z [0]", all (\z -> diag Nothing z == 0) [0 .. 100])] )

  group c "section 7.8: the wff (forall a) [not a = 2 => (exists b) a = b x b] is false"
    [ ("a = 3: no b with b x b = 3 (b <= 3; b >= 4 gives b x b >= 16)",
       null [b | b <- [0 .. 3 :: Integer], b * b == 3] && 4 * 4 > (3 :: Integer)) ]

  let ab = [(a, b) | a <- [0 .. 100 :: Integer], b <- [0 .. 100]]
  group c "footnote of p. 131: the axioms hold in N (a, b <= 100)"
    ( [ ("a + 1 = b + 1 => a = b; a x (b + 1) = (a x b) + a; a + (b + 1) = (a + b) + 1 " ++ show (a, b),
         (a + 1 /= b + 1 || a == b) && a * (b + 1) == a * b + a && a + (b + 1) == (a + b) + 1)
      | (a, b) <- ab ]
      ++ [ ("not 0 = a + 1; a + 0 = a; a x 0 = 0, a = " ++ show a, 0 /= a + 1 && a + 0 == a && a * 0 == 0)
         | a <- [0 .. 100 :: Integer] ]
      ++ [("0 + 1 = 1", 0 + 1 == (1 :: Integer))]
      ++ [ ("(...((1 + 1) + 1) ... + 1) = x with x ones, x = " ++ show x, foldl (+) 1 (replicate (x - 1) 1) == toInteger x)
         | x <- [1 .. 100 :: Int] ] )

  let p = At 0
      q = At 1
      r = At 2
      small = formulas 1 [0, 1]
  group c "exercise 7-62 (b), (c) on bounded depth"
    ( [ ("(b) A in A~, A~~ = A~ for A = " ++ show a,
         all (`elem` closure 2 a) a && closure 2 (closure 2 a) == closure 2 a)
      | a <- map (: []) small ++ [[p, q], [And p q], [And (And p q) r]] ]
      ++ [ ("(c) (p & q) in {p, q}~, not in {p}~ union {q}~",
            And p q `elem` closure 2 [p, q] && And p q `notElem` (closure 2 [p] ++ closure 2 [q])) ] )

  group c "exercise 7-62 (d): A~ = B~ (read), not A~ = B"
    ( [ ("B = {p}: (p & p) in B~ - B", And p p `elem` closure 2 [p] && And p p `notElem` [p])
      , ("A~ = B~ with A = B = {p}", closure 2 [p] == closure 2 [p]) ]
      ++ [ ("A~ /= {p}, A = " ++ show a, closure 2 a /= [p]) | a <- subsets small ] )

  let fAt n = [0, 1, 2, 0, 0, 1, 2, 2] !! (n `mod` 8)
      craigA = [conj (n + 1) (At (fAt n)) | n <- [0 .. 2]]
  group c "exercise 7-62 (d), the hint: Craig's set"
    ( [ ("x, (x & x), ... interderivable (depth <= 2): conj " ++ show k ++ " " ++ show x,
         conj k x `elem` closure 2 [x] && x `elem` closure 2 [conj k x])
      | (k, x) <- [(k, a) | k <- [1 .. 3], a <- [p, q]] ++ [(k, And p q) | k <- [1, 2]] ]
      ++ [ ("membership by the shape agrees with the list, " ++ show w,
            inCraig fAt w == (w `elem` [conj (n + 1) (At (fAt n)) | n <- [0 .. 4]]))
         | w <- formulas 2 [0, 1, 2] ]
      ++ [ ("Craig's set and Val f = {p, q, r}: the same consequences of depth <= 2",
            closure 2 craigA == closure 2 [p, q, r]
            && length (closure 2 [p, q, r]) == length (formulas 2 [0, 1, 2])) ] )

  finish c "ch05-07-productive"
  where
    unJust (Just v) = v
    unJust Nothing = error "psi undefined in the iteration"
    subsets [] = [[]]
    subsets (x : xs) = let s = subsets xs in s ++ map (x :) s
