-- A small random generator (splitmix64)

newtype Gen = Gen Word64

next :: Gen -> (Word64, Gen)
next (Gen s) = (z3, Gen s')
  where
    s' = s + 0x9e3779b97f4a7c15
    z1 = (s' `xor` (s' `shiftR` 30)) * 0xbf58476d1ce4e5b9
    z2 = (z1 `xor` (z1 `shiftR` 27)) * 0x94d049bb133111eb
    z3 = z2 `xor` (z2 `shiftR` 31)

below :: Int -> Gen -> (Int, Gen)
below n g = let (w, g') = next g in (fromIntegral (w `mod` fromIntegral n), g')

draws :: Int -> (Gen -> (a, Gen)) -> Gen -> ([a], Gen)
draws 0 _ g = ([], g)
draws k f g = let (a, g1) = f g; (as, g2) = draws (k - 1) f g1 in (a : as, g2)

fib :: Int -> Int
fib k = fibs !! k
  where fibs = 0 : 1 : zipWith (+) fibs (drop 1 fibs)

