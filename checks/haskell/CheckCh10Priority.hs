-- Theorem V (Shoenfield) on toy programs

-- | A world: C listed by f (f !! z), programs prog y (x', y') = output and
-- length, or Nothing.
data World = World
  { wf :: [Int], wprog :: Int -> (Int, Int) -> Maybe (Int, Int), wY :: Int }

xs10 :: [Int]
xs10 = [0 .. 9]

finv :: World -> Int -> Maybe Int
finv w x = lookup x (zip (wf w) [0 ..])

-- | psi(<x, y>) = 1 - output when f(z) = x and the length w < z.
psiW :: World -> (Int, Int) -> Maybe Int
psiW w (x, y) = do
  z <- finv w x
  (o, len) <- wprog w y (x, y)
  if len < z && o `elem` [0, 1] then Just (1 - o) else Nothing

inA, inB :: World -> (Int, Int) -> Bool
inA w p = psiW w p == Just 1
inB w p = psiW w p == Just 0

-- | Random worlds; program 0 is lambda z [0] (item 3), the last program is
-- a candidate separator: correct off its diagonal, random on it.
mkWorld :: Int -> World
mkWorld s =
  let g0 = Gen (fromIntegral (330000 + 104729 * s))
      (perm, g1) = shuffleL xs10 g0
      (csize, g2) = below 8 g1
      fs = take (csize + 2) perm
      ytot = 5
      (table, g3) = draws (ytot * 10) cell g2
      (lens0, g4) = draws 10 (below 9) g3
      (diag, _) = draws 10 dcell g4
      base y (x', y')
        | y == 0 = Just (0, lens0 !! x')
        | y' == y = table !! (y * 10 + x')
        | otherwise = table !! (y * 10 + x')
      w0 = World fs base ytot
      sepY = ytot - 1
      prog y (x', y')
        | y /= sepY = base y (x', y')
        | y' == sepY = fmap (\(o, l) -> (o `mod` 2, l)) (diag !! x')
        | inA w0 (x', y') = Just (1, 3)
        | inB w0 (x', y') = Just (0, 3)
        | otherwise = Just (x' `mod` 2, 2)
  in World fs prog ytot
  where
    cell g = let (k, h1) = below 4 g; (len, h2) = below 9 h1
             in (if k == 3 then Nothing else Just (min k 1, len), h2)
    dcell g = let (o, h1) = below 2 g; (len, h2) = below 10 h1 in (Just (o, len), h2)

shuffleL :: [a] -> Gen -> ([a], Gen)
shuffleL [] g = ([], g)
shuffleL xs g = let (i, g1) = below (length xs) g
                    (rest, g2) = shuffleL (take i xs ++ drop (i + 1) xs) g1
                in (xs !! i : rest, g2)

worlds :: [World]
worlds = map mkWorld [1 .. 3000]

-- | A program is a separator: total, {0, 1}-valued on all <x', y'>, 1 on A,
-- 0 on B.
separates :: World -> Int -> Bool
separates w y1 = and [ case wprog w y1 p of
                         Just (o, _) -> o `elem` [0, 1] && (not (inA w p) || o == 1) && (not (inB w p) || o == 0)
                         Nothing -> False
                     | p <- [(x', y') | x' <- xs10, y' <- [0 .. wY w - 1]] ]

shoenfieldChecks :: [(String, Bool)]
shoenfieldChecks = concatMap one (zip [1 :: Int ..] worlds) ++ global
  where
    inC w x = x `elem` wf w
    one (s, w) =
      let tag t = "world " ++ show s ++ ": " ++ t
          item1 = [ (tag "item 1: <x, y> in A <=> x in C & P_y gives 0 in fewer than f^(-1)(x) steps",
                     inA w (x, y) == (case (finv w x, wprog w y (x, y)) of
                                        (Just z, Just (0, len)) -> len < z
                                        _ -> False))
                  | x <- xs10, y <- [0 .. wY w - 1] ]
          u x = maybe 0 snd (wprog w 0 (x, 0))
          item3 = [ (tag "item 3: x in C <=> <x, y_0> in A or f(z) = x for some z <= u",
                     inC w x == (inA w (x, 0) || any (\z -> z < length (wf w) && wf w !! z == x) [0 .. u x]))
                  | x <- xs10 ]
          sepY = wY w - 1
          g x = maybe 0 snd (wprog w sepY (x, sepY))
          item5 = if separates w sepY
                    then [ (tag "item 5: a separator works at least f^(-1)(x) steps at <x, y_1>",
                            all (\x -> maybe True (\z -> g x >= z) (finv w x)) xs10)
                         , (tag "item 5: x in C <=> (exists z)[z <= g(x) & f(z) = x]",
                            all (\x -> inC w x == any (\z -> z < length (wf w) && wf w !! z == x) [0 .. g x]) xs10) ]
                    else []
      in item1 ++ item3 ++ item5
    strict3 w x = inC w x == (inA w (x, 0) || any (\z -> z < length (wf w) && wf w !! z == x) [0 .. maybe 0 snd (wprog w 0 (x, 0)) - 1])
    strict5 w = let sepY = wY w - 1; g x = maybe 0 snd (wprog w sepY (x, sepY))
                in all (\x -> inC w x == any (\z -> z < length (wf w) && wf w !! z == x) [0 .. g x - 1]) xs10
    global =
      [ ("some separators occur", length (filter (\w -> separates w (wY w - 1)) worlds) > 100)
      , ("some candidates fail to separate (fast on the diagonal)", any (\w -> not (separates w (wY w - 1))) worlds)
      , ("item 3 with z < u (refuted reading) fails in some world", any (\w -> not (all (strict3 w) xs10)) worlds)
      , ("item 5 with z < g(x) (printed) fails for some separator",
         any (\w -> separates w (wY w - 1) && not (strict5 w)) worlds) ]

