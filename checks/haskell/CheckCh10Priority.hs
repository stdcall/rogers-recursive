-- Theorem III: the Friedberg-Muchnik construction

-- | <x, P, N, t>: x appears in W_j^D at step t when P subset D, N cap D = 0.
data Axiom = Axiom { axX :: Int, axP :: [Int], axN :: [Int], axT :: Int }

type Machine = [Axiom]

fits :: [Int] -> Axiom -> Bool
fits d a = all (`elem` d) (axP a) && not (any (`elem` d) (axN a))

-- | The first axiom showing x in W^D within n steps.
witness :: Machine -> Int -> [Int] -> Int -> Maybe Axiom
witness m n d x = case [a | a <- m, axX a == x, axT a <= n, fits d a] of
  (a : _) -> Just a
  [] -> Nothing

inFull :: Machine -> [Int] -> Int -> Bool
inFull m d x = any (\a -> axX a == x && fits d a) m

data List = List { plus :: [Int], minus :: [Int], marks :: [(Int, Int)] }

emptyList :: List
emptyList = List [] [] []

firstFree :: List -> Int
firstFree l = case plus l ++ minus l ++ map snd (marks l) of
  [] -> 0
  xs -> maximum xs + 1

posOf :: List -> Int -> Int
posOf l i = maybe (error "no marker") id (lookup i (marks l))

setMark :: Int -> Int -> List -> List
setMark i p l = l { marks = (i, p) : filter ((/= i) . fst) (marks l) }

-- | A move or an introduction: (list 0 = A / 1 = B, marker, position).
data Event = Placed Int Int Int | Acted Int Int Int [Int]

data St = St
  { sA :: List, sB :: List, events :: [Event], stageSets :: [([Int], [Int])] }

-- | Move markers is (in increasing order) to the free numbers of a list.
moveDown :: [Int] -> Int -> List -> ([Event], List)
moveDown is lst l0 = foldl' step ([], l0) is
  where
    step (es, l) i = let p = firstFree l in (es ++ [Placed lst i p], setMark i p l)

-- | One half stage: own list `own` (index lo), the other list `oth`;
-- `movable j` lists the markers of the other list moved when [j] acts.
half :: Int -> [Machine] -> Int -> (Int -> [Int]) -> List -> List
     -> ([Event], List, List)
half lo machines n movable own oth =
  let p0 = firstFree own
      own1 = setMark n p0 own
      intro = Placed lo n p0
      d = plus oth
      cands = [ (posOf own1 j, j, a)
                   | j <- [0 .. n]
                   , let a' = posOf own1 j
                   , a' `notElem` plus own1
                   , Just a <- [witness (machineAt j) n d a'] ]
      machineAt j = if j < length machines then machines !! j else []
  in case cands of
       [] -> ([intro], own1, oth)
       _ ->
         let (p, j, a) = minimumBy (comparing (\(q, _, _) -> q)) cands in
         let own2 = own1 { plus = p : plus own1 }
             mins = [y | y <- axN a, y `notElem` plus oth]
             oth1 = oth { minus = nub (mins ++ minus oth) }
             (moves, oth2) = moveDown (movable j) (1 - lo) oth1
         in ([intro, Acted lo j p mins] ++ moves, own2, oth2)

-- | Stages 2n + 1 and 2n + 2 for n = 0, ..., k - 1.
runFM :: [Machine] -> [Machine] -> Int -> St
runFM ma mb k = foldl' stagePair (St emptyList emptyList [] [([], [])]) [0 .. k - 1]
  where
    stagePair st n =
      let (e1, a1, b1) = half 0 ma n (\j -> [j .. n - 1]) (sA st) (sB st)
          sets1 = (plus a1, plus b1)
          (e2, b2, a2) = half 1 mb n (\j -> [j + 1 .. n]) b1 a1
          sets2 = (plus a2, plus b2)
      in St a2 b2 (events st ++ e1 ++ e2) (stageSets st ++ [sets1, sets2])

-- | Random machine: axioms with x <= 12, |P|, |N| <= 2, t <= 10, plus
-- some "x in W^D <=> x not in D" axioms.
randomMachine :: Gen -> (Machine, Gen)
randomMachine g0 =
  let (k, g1) = below 7 g0
      (axs, g2) = draws (k + 1) ax g1
      (dk, g3) = below 4 g2
      (diag, g4) = draws dk dax g3
  in (axs ++ diag, g4)
  where
    ax g = let (x, h1) = below 13 g
               (np, h2) = below 3 h1
               (ps, h3) = draws np (below 13) h2
               (nn, h4) = below 3 h3
               (ns, h5) = draws nn (below 13) h4
               (t, h6) = below 10 h5
           in (Axiom x (nub ps) (nub ns) (t + 1), h6)
    dax g = let (x, h1) = below 13 g; (t, h2) = below 10 h1 in (Axiom x [] [x] (t + 1), h2)

data Run = Run { runA :: [Machine], runB :: [Machine], early :: St, late :: St }

mkRun :: Int -> Run
mkRun s =
  let g0 = Gen (fromIntegral (910000 + 7919 * s))
      (ma, g1) = draws 5 randomMachine g0
      (mb, _) = draws 5 randomMachine g1
  in Run ma mb (runFM ma mb 45) (runFM ma mb 75)

runs :: [Run]
runs = map mkRun [1 .. 400]

finalPositions :: Int -> St -> [(Int, Int)]
finalPositions lo st = sort (marks (if lo == 0 then sA st else sB st))

positionsOf :: Int -> Int -> St -> [Int]
positionsOf lo i st = nub [p | Placed l j p <- events st, l == lo, j == i]

machineOf :: [Machine] -> Int -> Machine
machineOf ms j = if j < length ms then ms !! j else []

fmChecks :: [(String, Bool)]
fmChecks = concatMap one (zip [1 :: Int ..] runs) ++ global
  where
    one (s, r) =
      let st = early r; lt = late r
          aSet = plus (sA st); bSet = plus (sB st)
          tag w = "run " ++ show s ++ ": " ++ w
          req1 = [ (tag ("f(" ++ show x ++ ") in A <=> f(x) in W_x^B"),
                    (p `elem` aSet) == inFull (machineOf (runA r) x) bSet p)
                 | (x, p) <- finalPositions 0 st ]
          req2 = [ (tag ("g(" ++ show x ++ ") in B <=> g(x) in W_x^A"),
                    (p `elem` bSet) == inFull (machineOf (runB r) x) aSet p)
                 | (x, p) <- finalPositions 1 st ]
          stable = [ (tag "the run continued to 150 stages changes no marker and no plus",
                      and [ lookup i (marks (sA lt)) == Just p | (i, p) <- marks (sA st) ]
                      && and [ lookup i (marks (sB lt)) == Just p | (i, p) <- marks (sB st) ]
                      && sort (plus (sA lt)) == sort aSet && sort (plus (sB lt)) == sort bSet) ]
          restraint = [ (tag "minuses of the final action of a final marker stay out of the plus set",
                         all (`notElem` (if lo == 0 then bSet else aSet)) mins)
                      | Acted lo j p mins <- events st
                      , lookup j (marks (if lo == 0 then sA st else sB st)) == Just p ]
          down = [ (tag "markers move only down", and (zipWith (<) ps (drop 1 ps)))
                 | lo <- [0, 1], i <- map fst (marks (if lo == 0 then sA st else sB st))
                 , let ps = [p | Placed l j p <- events st, l == lo, j == i] ]
          fibb = [ (tag ("marker " ++ show k ++ " of the priority order: <= F(k + 2) positions"),
                    length (positionsOf (k `mod` 2) (k `div` 2) st) <= fib (k + 2))
                 | k <- [0 .. 2 * 44 + 1] ]
          -- The lemma for the sequence A'_n = A_(2n) of the continued run
          -- (its union is the final A): from the first n at which an
          -- axiom valid for A is available (t <= n, P subset A'_n) on,
          -- a appears within n steps in W_z^(A'_n).
          lemma = [ (tag ("lemma of p. 214 for W_" ++ show z ++ ", a = " ++ show a),
                     let setAt n = fst (stageSets lt !! (2 * n))
                         ok n = case witness (machineOf (runA r) z) n (setAt n) a of
                                  Just _ -> True
                                  Nothing -> False
                         valid = [ax | ax <- machineOf (runA r) z, axX ax == a, fits aSet ax]
                         ready n = any (\ax -> axT ax <= n && all (`elem` setAt n) (axP ax)) valid
                         m0 = foldr const 75 [n | n <- [0 .. 74], ready n]
                     in m0 < 75 && all ok [m0 .. 74])
                  | z <- [0 .. 4], a <- [0 .. 12], inFull (machineOf (runA r) z) aSet a ]
      in req1 ++ req2 ++ stable ++ restraint ++ down ++ fibb ++ lemma
    global =
      [ ("some run moves markers", any (\r -> length [() | Placed _ _ _ <- events (early r)] > 2 * 45) runs)
      , ("[0]_1 never moves, [0]_2 moves at most once (all runs)",
         all (\r -> length (positionsOf 0 0 (early r)) == 1 && length (positionsOf 1 0 (early r)) <= 2) runs)
      , ("a minus later gets a plus in some run (remark of p. 215)",
         any (\r -> let st = early r in
                any (\y -> y `elem` plus (sA st)) (minus (sA st))
                || any (\y -> y `elem` plus (sB st)) (minus (sB st))) runs)
      , ("some marker reaches its third position", any (\r -> any (\k -> length (positionsOf (k `mod` 2) (k `div` 2) (early r)) >= 3) [0 .. 20]) runs)
      , ("Fibonacci numbers 1, 2, 3, 5, 8 of the footnote", map (\k -> fib (k + 2)) [0 .. 4] == [1, 2, 3, 5, 8]) ]

