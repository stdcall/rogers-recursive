-- Theorem IV (Young): the step with h

youngChecks :: [(String, Bool)]
youngChecks =
  [ (show (gs, d, m, n), ok)
  | gs <- injections 3 5
  , d <- subsequences [0 .. 4]
  , let b = [x | x <- [0 .. 2], gs !! x `elem` d]
  , m <- [0 .. 4], m `notElem` d
  , n <- [0 .. 4], n `notElem` d, n `notElem` gs
  , let h x = if gs !! x /= m then gs !! x else n
        dm = m : d
        ok = length (nub (map h [0 .. 2])) == 3
             && and [ (x `elem` b) == (h x `elem` dm) | x <- [0 .. 2] ] ]
  ++ [ ("A <=_1 D u {m} via f when m not in f(N)",
        and [ (x `elem` [y | y <- [0 .. 2], fs !! y `elem` d]) == (fs !! x `elem` (m : d))
            | fs <- injections 3 5, d <- subsequences [0 .. 4]
            , m <- [0 .. 4], m `notElem` d, m `notElem` fs, x <- [0 .. 2] ]) ]
  where
    injections :: Int -> Int -> [[Int]]
    injections 0 _ = [[]]
    injections k r = [ y : ys | ys <- injections (k - 1) r, y <- [0 .. r - 1], y `notElem` ys ]

