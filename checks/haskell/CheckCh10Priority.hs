-- Theorem VI: spectra of sentences of L_0

data F = Eq Int Int | Not F | And F F | Or F F | Imp F F | Iff F F | All Int F | Ex Int F

holds :: Int -> [(Int, Int)] -> F -> Bool
holds m env f = case f of
  Eq a b -> val a == val b
  Not p -> not (holds m env p)
  And p q -> holds m env p && holds m env q
  Or p q -> holds m env p || holds m env q
  Imp p q -> not (holds m env p) || holds m env q
  Iff p q -> holds m env p == holds m env q
  All v p -> all (\e -> holds m ((v, e) : env) p) [0 .. m - 1]
  Ex v p -> any (\e -> holds m ((v, e) : env) p) [0 .. m - 1]
  where val v = maybe (error "free variable") id (lookup v env)

spectrumUpTo :: Int -> F -> [Int]
spectrumUpTo bound f = [m | m <- [1 .. bound], holds m [] f]

quantifiers :: F -> Int
quantifiers f = case f of
  Eq _ _ -> 0
  Not p -> quantifiers p
  And p q -> quantifiers p + quantifiers q
  Or p q -> quantifiers p + quantifiers q
  Imp p q -> quantifiers p + quantifiers q
  Iff p q -> quantifiers p + quantifiers q
  All _ p -> 1 + quantifiers p
  Ex _ p -> 1 + quantifiers p

bigAnd, bigOr :: [F] -> F
bigAnd = foldr1 And
bigOr = foldr1 Or

-- | F_1 = (exists a) a = a; F_n = (exists a_1) ... (exists a_n) [all a_i distinct].
fN :: Int -> F
fN 1 = Ex 1 (Eq 1 1)
fN n = foldr Ex (bigAnd [Not (Eq i j) | i <- [1 .. n], j <- [i + 1 .. n]]) [1 .. n]

eN :: Int -> F
eN 0 = All 1 (Not (Eq 1 1))
eN n = And (fN n) (Not (fN (n + 1)))

sentenceI, sentenceII, sentenceIII :: F
sentenceI = All 1 (Ex 2 (Not (Eq 1 2)))
sentenceII = Ex 1 (Ex 2 (Not (Eq 1 2)))
sentenceIII = Not (Ex 1 (All 2 (Imp (All 3 (Or (Eq 3 1) (Eq 3 2))) (Eq 2 1))))

-- | Random sentence with exactly q quantifiers, atoms over bound variables.
randomSentence :: Int -> Gen -> (F, Gen)
randomSentence q g0 = let (v, g1) = below 2 g0 in quant (v == 0) q [] 1 g1
  where
    quant isAll k scope fresh g =
      let (body, g') = gen (k - 1) (fresh : scope) (fresh + 1) g
      in ((if isAll then All else Ex) fresh body, g')
    gen k scope fresh g
      | k == 0 = let (c, g1) = below 4 g in
          if c == 0 then let (p, g2) = atom scope g1 in (Not p, g2)
          else if c == 1 then let (p, g2) = atom scope g1; (r, g3) = atom scope g2 in (Or p r, g3)
          else atom scope g1
      | otherwise =
          let (c, g1) = below 6 g in
          if c <= 1 then let (b, g2) = below 2 g1 in quant (b == 0) k scope fresh g2
          else let (k1, g2) = below (k + 1) g1
                   (p, g3) = gen k1 scope fresh g2
                   (r, g4) = gen (k - k1) scope (fresh + k1) g3
                   (con, g5) = below 5 g4
               in ([And p r, Or p r, Imp p r, Iff p r, And (Not p) r] !! con, g5)
    atom scope g = let (i, g1) = below (length scope) g; (j, g2) = below (length scope) g1
                   in (Eq (scope !! i) (scope !! j), g2)

-- | Sets of naturals that are finite or cofinite: (finite part, cofinite?)
-- within the universe 0 .. 5, beyond it all in or all out.
type FC = ([Int], Bool)

memFC :: FC -> Int -> Bool
memFC (d, co) x = if x <= 5 then x `elem` d else co

-- | A set given by its members up to 8 is included in another (both
-- constant beyond 5).
subFC :: FC -> FC -> Bool
subFC a b = all (\x -> not (memFC a x) || memFC b x) [0 .. 8]

complFC :: FC -> FC
complFC (d, co) = ([x | x <- [0 .. 5], x `notElem` d], not co)

